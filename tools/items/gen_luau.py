    for cat, it in D.all_items():
        has_mesh = cat in D.MODEL_CATEGORIES
        e = dict(category=cat, mesh=Raw("PLACEHOLDER") if has_mesh else None, icon=Raw("PLACEHOLDER"))
        if has_mesh:
            e["texture"] = "FishAtlas" if cat == "Fish" else "PropsAtlas"
            e["meshFile"] = f"items/models/{it['id']}.obj"
        e["iconFile"] = f"items/icons/{it['id']}.png"
