class Raw(str):
    """Emit as-is (e.g. Color3.fromRGB(...))."""


def num(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, int):
        return f"{v:_}" if abs(v) >= 10_000 else str(v)
    r = round(v, 6)
    return str(int(r)) if r == int(r) and abs(r) < 1e15 and not isinstance(v, float) else repr(r)


def lua(v, depth=1):
    if isinstance(v, Raw):
        return str(v)
    if v is None:
        return "nil"
    if isinstance(v, (bool, int, float)):
        return num(v)
    if isinstance(v, str):
        return '"' + v.replace("\\", "\\\\").replace('"', '\\"') + '"'
    if isinstance(v, (list, tuple)):
        if all(not isinstance(x, (dict, list, tuple)) for x in v):
            return "{ " + ", ".join(lua(x) for x in v) + " }"
        inner = ",\n".join(TAB * (depth + 1) + lua(x, depth + 1) for x in v)
        return "{\n" + inner + ",\n" + TAB * depth + "}"
    if isinstance(v, dict):
        if all(not isinstance(x, (dict, list, tuple)) for x in v.values()) and len(v) <= 4 and \
                sum(len(str(x)) for x in v.values()) < 60:
            return "{ " + ", ".join(f"{k} = {lua(x)}" for k, x in v.items()) + " }"
        inner = "\n".join(TAB * (depth + 1) + f"{k} = {lua(x, depth + 1)}," for k, x in v.items())
        return "{\n" + inner + "\n" + TAB * depth + "}"
    raise TypeError(v)


def color(c):
    return Raw(f"Color3.fromRGB({c[0]}, {c[1]}, {c[2]})")


def item_list(items, keys):
    out = []
    for i, it in enumerate(items):
        row = {}
        for k in keys:
            if k == "order":
                row["order"] = it.get("order", i + 1)
            elif k in it:
                row[k] = it[k]
        out.append(row)
    return out


def write(name, header, body):
    path = os.path.join(OUT, name + ".luau")
    with open(path, "w") as fh:
        fh.write("--[[\n" + header.strip("\n") + "\n\n\tGENERATED by tools/items/gen_luau.py from tools/items/item_data.py.\n"
                 "\tTo change numbers, edit item_data.py and re-run the generator (or edit here and keep both in sync).\n]]\n\n")
        fh.write(body.strip("\n") + "\n")
    return path


def list_module(name, var, header, items, keys, extra=""):
    body = f"local {var} = {{}}\n\n{var}.List = {lua(item_list(items, keys))}\n\n" \
           f"-- Quick lookup: {var}.ById[\"some_id\"]\n{var}.ById = {{}}\nfor _, item in ipairs({var}.List) do\n" \
           f"\ttable.freeze(item)\n\t{var}.ById[item.id] = item\nend\n\ntable.freeze({var}.List)\ntable.freeze({var}.ById)\n" \
           f"{extra}\nreturn {var}"
    return write(name, header, body)


